#!/usr/bin/env python3
"""Collect user-facing strings from the Swift sources into the English strings table.

Keeps existing entries, adds new ones, and lists keys that no longer appear in the code.
Run it after changing UI text: python3 Scripts/extract-strings.py
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ROOT / "Sources"
OUTPUT = ROOT / "Localizations" / "en.lproj" / "Localizable.strings"

# Calls whose first string literal is a localisable key.
CALLS = [
    "Text",
    "Button",
    "Toggle",
    "Picker",
    "Label",
    "LabeledContent",
    "Section",
    "SwiftUI.Section",
    "TextField",
    "ContentUnavailableView",
    "CommandMenu",
    "Window",
    "MonoRow",
    "PanelCard",
    "PanelRow",
    "PillButton",
    "FormFooter",
    "confirmationDialog",
    "Stepper",
    "ProgressView",
]
MODIFIERS = ["help", "accessibilityLabel", "navigationTitle", "accessibilityValue"]
STRING = r'"((?:[^"\\]|\\.)*)"'
CALL_RE = re.compile(rf"(?<![\w.])(?:{'|'.join(re.escape(c) for c in CALLS)})\(\s*{STRING}")
MOD_RE = re.compile(rf"\.(?:{'|'.join(MODIFIERS)})\(\s*{STRING}")
VERBATIM_RE = re.compile(r"Text\(\s*verbatim:")
LOCALIZING_RE = re.compile(r"(?:localizing|LocalizedStringKey)\(")
RETURN_RE = re.compile(rf"return\s+{STRING}\s*$")
STATE_LABEL_RE = re.compile(rf"(?:case\s+\.\w+(?:\(let \w+\))?\s*:\s*return|=)\s+{STRING}")


def to_key(literal: str) -> str:
    key = re.sub(r"\\\((?:[^()]|\([^()]*\))*\)", "%@", literal)
    return key


def should_skip(key: str) -> bool:
    if not key.strip():
        return True
    return re.fullmatch(r"[%@\s\d.,:%lld-]+", key) is not None


def collect() -> dict[str, set[str]]:
    keys: dict[str, set[str]] = {}
    for path in sorted(SOURCES.rglob("*.swift")):
        text = path.read_text()
        rel = str(path.relative_to(ROOT))
        for regex in (CALL_RE, MOD_RE):
            for match in regex.finditer(text):
                key = to_key(match.group(1))
                if should_skip(key):
                    continue
                keys.setdefault(key, set()).add(rel)
        # Display names the app shows through Text(localizing:). Only the bodies of those
        # properties are scanned, so wire-level descriptions stay out of the table.
        if path.name in LABEL_SOURCES:
            for body in label_bodies(text):
                for m in re.finditer(STRING, body):
                    key = to_key(m.group(1))
                    if not should_skip(key) and len(key) > 1 and "%" not in key:
                        keys.setdefault(key, set()).add(rel)
    return keys


LABEL_SOURCES = {
    "Model.swift",
    "Status.swift",
    "Decoders.swift",
    "BudsController.swift",
    "BluetoothTransport.swift",
}
LABEL_PROPERTIES = (
    "displayName",
    "description",
    "label",
    "errorDescription",
    "resultName",
)


def label_bodies(text: str):
    """Yield the bodies of `var displayName: String { … }` style properties."""
    names = "|".join(LABEL_PROPERTIES)
    for m in re.finditer(rf"var (?:{names}): String\?? \{{", text):
        depth, i = 1, m.end()
        while i < len(text) and depth:
            depth += {"{": 1, "}": -1}.get(text[i], 0)
            i += 1
        yield text[m.end() : i]


def parse(path: pathlib.Path) -> dict[str, str]:
    if not path.exists():
        return {}
    entries = {}
    for m in re.finditer(
        r'^\s*"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)";',
        path.read_text(),
        re.MULTILINE,
    ):
        entries[m.group(1)] = m.group(2)
    return entries


def main() -> int:
    keys = collect()
    existing = parse(OUTPUT)
    obsolete = sorted(k for k in existing if k not in keys)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "/* English base strings for Mirinae. Generated by Scripts/extract-strings.py; edit the",
        "   values if the English needs fixing, then run the script again to keep it sorted. */",
        "",
    ]
    for key in sorted(keys, key=str.lower):
        value = existing.get(key, key)
        lines.append(f"/* {', '.join(sorted(keys[key]))} */")
        lines.append(f'"{key}" = "{value}";')
        lines.append("")
    OUTPUT.write_text("\n".join(lines))
    print(f"{len(keys)} keys written to {OUTPUT.relative_to(ROOT)}")
    if obsolete:
        print("No longer in the code (removed):")
        for k in obsolete:
            print("  ", k)
    return 0


if __name__ == "__main__":
    sys.exit(main())
